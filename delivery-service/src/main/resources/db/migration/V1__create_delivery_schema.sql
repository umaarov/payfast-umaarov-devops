CREATE TABLE couriers (
    id UUID PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    phone VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL,
    max_active_deliveries INTEGER NOT NULL,
    active_deliveries INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_couriers_phone UNIQUE (phone),
    CONSTRAINT ck_couriers_status CHECK (status IN ('AVAILABLE', 'OFF_DUTY')),
    CONSTRAINT ck_couriers_capacity_positive CHECK (max_active_deliveries > 0),
    CONSTRAINT ck_couriers_active_non_negative CHECK (active_deliveries >= 0)
);

CREATE TABLE deliveries (
    id UUID PRIMARY KEY,
    order_id UUID NOT NULL,
    tracking_number VARCHAR(32) NOT NULL,
    courier_id UUID NOT NULL,
    recipient_name VARCHAR(120) NOT NULL,
    recipient_phone VARCHAR(32) NOT NULL,
    city VARCHAR(80) NOT NULL,
    address_line VARCHAR(255) NOT NULL,
    status VARCHAR(16) NOT NULL,
    failure_reason VARCHAR(255),
    version BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_deliveries_order UNIQUE (order_id),
    CONSTRAINT uq_deliveries_tracking_number UNIQUE (tracking_number),
    CONSTRAINT fk_deliveries_courier FOREIGN KEY (courier_id) REFERENCES couriers (id),
    CONSTRAINT ck_deliveries_status CHECK (status IN (
        'ASSIGNED', 'PICKED_UP', 'IN_TRANSIT', 'DELIVERED', 'FAILED', 'CANCELLED'))
);

CREATE INDEX idx_deliveries_courier_status ON deliveries (courier_id, status);
CREATE INDEX idx_deliveries_status ON deliveries (status);

CREATE TABLE outbox_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target VARCHAR(16) NOT NULL,
    path VARCHAR(200) NOT NULL,
    payload VARCHAR(4000) NOT NULL,
    state VARCHAR(16) NOT NULL,
    attempts INTEGER NOT NULL,
    last_error VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_outbox_target CHECK (target IN ('TRACKING', 'ORDER')),
    CONSTRAINT ck_outbox_state CHECK (state IN ('PENDING', 'SENT', 'REJECTED'))
);

CREATE INDEX idx_outbox_dispatch ON outbox_events (target, state, id);
